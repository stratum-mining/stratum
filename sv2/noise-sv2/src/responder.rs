// # Responder Role
//
// Manages the [`Responder`] role in the Noise protocol handshake for secure communication between
// Sv2 roles. The responder is responsible for handling incoming handshake messages from the
// [`crate::Initiator`] (e.g., a mining proxy) and respond with the appropriate cryptographic
// data.
//
// The [`Responder`] role is equipped with utilities for handling elliptic curve Diffie-Hellman
// (ECDH) key exchanges, decrypting messages, and securely managing cryptographic state during the
// handshake phase. The responder's responsibilities include:
//
// - Generating an ephemeral key pair for the handshake.
// - Using the [`secp256k1`] elliptic curve for ECDH to compute a shared secret based on the
//   initiator's public key.
// - Decrypting and processing incoming handshake messages from the initiator.
// - Managing state transitions, including updates to the handshake hash, chaining key, and
//   encryption key as the session progresses.
//
// ## Usage
// The responder role is typically used by an upstream Sv2 role (e.g., a remote mining pool) to
// respond to an incoming handshake initiated by a downstream role (e.g., a local mining proxy).
// After receiving the initiator's public key, the responder computes a shared secret, which is
// used to securely encrypt further communication.
//
// The [`Responder`] struct implements the [`HandshakeOp`] trait, which defines the core
// cryptographic operations during the handshake. It ensures secure communication by supporting
// the [`ChaCha20Poly1305`] cipher, providing both confidentiality and message authentication for
// all subsequent communication.
//
// ### Secure Data Erasure
//
// The [`Responder`] includes functionality for securely erasing sensitive cryptographic material,
// ensuring that private keys and other sensitive data are wiped from memory when no longer needed.
// The [`Drop`] trait is implemented to automatically trigger secure erasure when the [`Responder`]
// instance goes out of scope, preventing potential misuse or leakage of cryptographic material.

use zeroize::Zeroize;

use crate::{
    cipher_state::{Cipher, CipherState},
    handshake::HandshakeOp,
    signature_message::SignatureNoiseMessage,
    AeadError, NoiseEngine, ELLSWIFT_ENCODING_SIZE, ENCRYPTED_ELLSWIFT_ENCODING_SIZE,
    ENCRYPTED_SIGNATURE_NOISE_MESSAGE_SIZE, INITIATOR_EXPECTED_HANDSHAKE_MESSAGE_SIZE,
    SIGNATURE_NOISE_MESSAGE_SIZE,
};
use alloc::{
    boxed::Box,
    string::{String, ToString},
    vec::Vec,
};
use chacha20poly1305::{ChaCha20Poly1305, Key, KeyInit};
use secp256k1::{ellswift::ElligatorSwift, Keypair};

/// Represents the state and operations of the responder in the Noise NX protocol handshake.
/// It handles cryptographic key exchanges, manages handshake state, and securely establishes
/// a connection with the initiator. The responder manages key generation, Diffie-Hellman exchanges,
/// message decryption, and state transitions, ensuring secure communication. Sensitive
/// cryptographic material is securely erased when no longer needed.
pub struct Responder {
    // Cipher used for encrypting and decrypting messages during the handshake.
    //
    // It is initialized once enough information is available from the handshake process.
    handshake_cipher: Option<ChaCha20Poly1305>,
    // Optional static key used in the handshake. This key may be derived from the pre-shared key
    // (PSK) or generated during the handshake.
    k: Option<[u8; 32]>,
    // Current nonce used in the encryption process.
    //
    // Ensures that the same plaintext encrypted twice will produce different ciphertexts.
    n: u64,
    // Chaining key used in the key derivation process to generate new keys throughout the
    // handshake.
    ck: [u8; 32],
    // Handshake hash which accumulates all handshake messages to ensure integrity and prevent
    // tampering.
    h: [u8; 32],
    // Ephemeral key pair generated by the responder for this session, used for generating the
    // shared secret with the initiator.
    e: Keypair,
    // Static key pair of the responder, the one its certificate covers: supplied by the caller
    // together with that certificate, or generated for this one handshake and certified at
    // construction.
    s: Keypair,
    // The `SIGNATURE_NOISE_MESSAGE` (spec 4.5.2) sent in the second handshake message.
    certificate: SignatureNoiseMessage,
}

impl core::fmt::Debug for Responder {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("Responder").finish()
    }
}

// Every handshake encryption goes through `encrypt_with_ad`, which takes `&mut self`, and
// `Responder` is deliberately not `Clone`, so the handshake key and its nonce counter cannot be
// duplicated or advanced from two places at once. See `Cipher` for the transport-mode counterpart.
impl CipherState<ChaCha20Poly1305> for Responder {
    fn get_k(&mut self) -> &mut Option<[u8; 32]> {
        &mut self.k
    }

    fn get_n(&self) -> u64 {
        self.n
    }

    fn set_n(&mut self, n: u64) {
        self.n = n;
    }

    fn set_k(&mut self, k: Option<[u8; 32]>) {
        self.k = k;
    }

    fn get_cipher(&mut self) -> &mut Option<ChaCha20Poly1305> {
        &mut self.handshake_cipher
    }
}

impl HandshakeOp<ChaCha20Poly1305> for Responder {
    fn name(&self) -> String {
        "Responder".to_string()
    }

    fn get_h(&mut self) -> &mut [u8; 32] {
        &mut self.h
    }

    fn get_ck(&mut self) -> &mut [u8; 32] {
        &mut self.ck
    }

    fn set_h(&mut self, data: [u8; 32]) {
        self.h = data;
    }

    fn set_ck(&mut self, data: [u8; 32]) {
        self.ck = data;
    }

    fn set_handshake_cipher(&mut self, cipher: ChaCha20Poly1305) {
        self.handshake_cipher = Some(cipher);
    }
}

impl Responder {
    /// Creates a new [`Responder`] instance with the provided authority keypair and certificate
    /// validity.
    ///
    /// Constructs a new [`Responder`] with the necessary cryptographic state for the Noise NX
    /// protocol handshake. It generates ephemeral and static key pairs for the responder and
    /// prepares the handshake state. The certificate over the static key is signed here with the
    /// authority keypair, valid from now for `cert_validity` seconds, and sent in
    /// [`Self::step_1`]. The [`Responder`] does not keep the authority keypair; the caller's
    /// copy is the caller's to erase.
    ///
    /// # Security
    ///
    /// A host that calls this for every connection holds the authority private key in memory
    /// and, in practice, in its configuration. The authority public key is what clients pin (spec
    /// 4.5.3, 4.7), and neither the spec nor this crate defines revocation, so a compromise of
    /// that host leaks a key that impersonates the operator to every client for as long as any of
    /// them keeps trusting it. The static key is generated here and discarded with the
    /// [`Responder`], so it cannot be certified in advance, and the certificate lifetime is
    /// whatever `cert_validity` says on the same host. Use it for development and testing. A
    /// server outside those should hold only a static key and a certificate issued where the
    /// authority private key is kept: see [`Self::from_certificate`].
    #[cfg(feature = "std")]
    pub fn new(authority_key: Keypair, cert_validity: u32) -> Box<Self> {
        let now = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_secs() as u32;
        Self::new_with_now_rng(authority_key, cert_validity, now, &mut rand::thread_rng())
    }

    /// Creates a new [`Responder`] instance with the provided authority keypair, certificate
    /// validity, the current time and a custom random number generator.
    ///
    /// See [`Self::new`] for more details.
    ///
    /// The current time and the custom random number generator should be provided in order to not
    /// implicitely rely on `std` and allow `no_std` environments to provide a hardware random
    /// number generator for example.
    #[inline]
    pub fn new_with_now_rng<R: rand::Rng + rand::CryptoRng + ?Sized>(
        mut authority_key: Keypair,
        cert_validity: u32,
        now: u32,
        rng: &mut R,
    ) -> Box<Self> {
        let s = Self::generate_key_with_rng(rng);
        let certificate = SignatureNoiseMessage::sign_with_rng(
            now,
            now.saturating_add(cert_validity),
            &s.x_only_public_key().0,
            &authority_key,
            rng,
        );
        authority_key.non_secure_erase();
        Self::from_certificate_with_rng(s, certificate, rng)
    }

    /// Creates a new [`Responder`] from its static keypair `s` and a certificate issued for it in
    /// advance.
    ///
    /// `certificate` is the `SIGNATURE_NOISE_MESSAGE` (spec 4.5.2): the certificate
    /// version, the validity window and the authority's Schnorr signature over those fields and
    /// the x-only public key of `s` (spec 4.5.3). [`Self::step_1`] sends it verbatim, so the
    /// validity window is the one the issuer chose and nothing on this host can extend it.
    ///
    /// This is the constructor for servers outside development and testing: the authority
    /// private key stays wherever the certificate was signed, and the host holds only `s` and the
    /// certificate. Rotating the static key means issuing a certificate for a new `s` and building
    /// responders from that pair; sessions already established are unaffected.
    ///
    /// Nothing is checked here. A certificate issued for another static key or by another
    /// authority, or one outside its validity window, is sent as is and rejected by every
    /// initiator that pins the authority public key.
    #[cfg(feature = "std")]
    pub fn from_certificate(s: Keypair, certificate: SignatureNoiseMessage) -> Box<Self> {
        Self::from_certificate_with_rng(s, certificate, &mut rand::thread_rng())
    }

    /// Creates a new [`Responder`] from its static keypair, a certificate issued for it in
    /// advance, and a custom random number generator for the ephemeral key.
    ///
    /// See [`Self::from_certificate`] for more details.
    ///
    /// The custom random number generator should be provided in order to not implicitely rely on
    /// `std` and allow `no_std` environments to provide a hardware random number generator for
    /// example.
    #[inline]
    pub fn from_certificate_with_rng<R: rand::Rng + rand::CryptoRng + ?Sized>(
        s: Keypair,
        certificate: SignatureNoiseMessage,
        rng: &mut R,
    ) -> Box<Self> {
        let mut self_ = Self {
            handshake_cipher: None,
            k: None,
            n: 0,
            ck: [0; 32],
            h: [0; 32],
            e: Self::generate_key_with_rng(rng),
            s,
            certificate,
        };
        Self::initialize_self(&mut self_);
        Box::new(self_)
    }

    /// Processes the first step of the Noise NX protocol handshake for the responder.
    ///
    /// This function manages the responder's side of the handshake after receiving the initiator's
    /// initial message. It processes the ephemeral public key provided by the initiator, derives
    /// the necessary shared secrets, and constructs the response message. The response includes
    /// the responder's ephemeral public key (in its ElligatorSwift-encoded form), the encrypted
    /// static public key, and the encrypted `SIGNATURE_NOISE_MESSAGE`: the certificate given to
    /// [`Self::from_certificate`], or the one [`Self::new`] signed. Additionally, it establishes
    /// the session ciphers for encrypting and decrypting further communication.
    ///
    /// On success, it returns a tuple containing the response message to be sent back to the
    /// initiator and a [`NoiseEngine`] instance, which is configured with the session ciphers for
    /// secure transmission of subsequent messages.
    ///
    /// On failure, the method returns an error if there is an issue during encryption, decryption,
    /// or any other step of the handshake process.
    ///
    /// The [`Responder`] is consumed: each step mixes into the handshake transcript, so it cannot
    /// be taken twice. Whether the step succeeds or fails, the remaining handshake secrets,
    /// including the ephemeral and static keypairs, are erased in place before the allocation is
    /// freed.
    pub fn step_1(
        mut self: Box<Self>,
        elligatorswift_theirs_ephemeral_serialized: [u8; ELLSWIFT_ENCODING_SIZE],
    ) -> Result<([u8; INITIATOR_EXPECTED_HANDSHAKE_MESSAGE_SIZE], NoiseEngine), AeadError> {
        // 4.5.1.2 Responder
        self.mix_hash(&elligatorswift_theirs_ephemeral_serialized[..]);
        self.decrypt_and_hash(&mut vec![])?;

        // 4.5.2.1 Responder
        let mut out = [0; INITIATOR_EXPECTED_HANDSHAKE_MESSAGE_SIZE];
        let elligatorswitf_ours_ephemeral = ElligatorSwift::from_pubkey(self.e.public_key());
        let elligatorswift_ours_ephemeral_serialized = elligatorswitf_ours_ephemeral.to_array();
        out[..ELLSWIFT_ENCODING_SIZE]
            .copy_from_slice(&elligatorswift_ours_ephemeral_serialized[..ELLSWIFT_ENCODING_SIZE]);

        // 3. calls `MixHash(e.public_key)`
        // what is here is not the public key encoded with ElligatorSwift, but the x-coordinate of
        // the public key (which is a point in the EC).

        self.mix_hash(&elligatorswift_ours_ephemeral_serialized);

        // 4. calls `MixKey(ECDH(e.private_key, re.public_key))`
        let e_private_key = self.e.secret_key();
        let elligatorswift_theirs_ephemeral =
            ElligatorSwift::from_array(elligatorswift_theirs_ephemeral_serialized);
        let mut ecdh_ephemeral = ElligatorSwift::shared_secret(
            elligatorswift_theirs_ephemeral,
            elligatorswitf_ours_ephemeral,
            e_private_key,
            secp256k1::ellswift::ElligatorSwiftParty::B,
            None,
        )
        .to_secret_bytes();
        self.mix_key(&ecdh_ephemeral);
        ecdh_ephemeral.zeroize();

        // 5. appends `EncryptAndHash(s.public_key)` (64 bytes encrypted elligatorswift  public key,
        //    16 bytes MAC)
        let mut encrypted_static_pub_k = vec![0; ELLSWIFT_ENCODING_SIZE];
        let elligatorswift_ours_static = ElligatorSwift::from_pubkey(self.s.public_key());
        let elligatorswift_ours_static_serialized: [u8; ELLSWIFT_ENCODING_SIZE] =
            elligatorswift_ours_static.to_array();
        encrypted_static_pub_k[..ELLSWIFT_ENCODING_SIZE]
            .copy_from_slice(&elligatorswift_ours_static_serialized[0..ELLSWIFT_ENCODING_SIZE]);
        self.encrypt_and_hash(&mut encrypted_static_pub_k)?;
        out[ELLSWIFT_ENCODING_SIZE..(ELLSWIFT_ENCODING_SIZE + ENCRYPTED_ELLSWIFT_ENCODING_SIZE)]
            .copy_from_slice(&encrypted_static_pub_k[..(ENCRYPTED_ELLSWIFT_ENCODING_SIZE)]);
        // note: 64+16+64 = 144

        // 6. calls `MixKey(ECDH(s.private_key, re.public_key))`
        let s_private_key = self.s.secret_key();
        let mut ecdh_static = ElligatorSwift::shared_secret(
            elligatorswift_theirs_ephemeral,
            elligatorswift_ours_static,
            s_private_key,
            secp256k1::ellswift::ElligatorSwiftParty::B,
            None,
        )
        .to_secret_bytes();
        self.mix_key(&ecdh_static[..]);
        ecdh_static.zeroize();

        // 7. appends `EncryptAndHash(SIGNATURE_NOISE_MESSAGE)` to the buffer
        let signature_noise_message: [u8; SIGNATURE_NOISE_MESSAGE_SIZE] = self.certificate.into();
        let mut signature_part = Vec::with_capacity(ENCRYPTED_SIGNATURE_NOISE_MESSAGE_SIZE);
        signature_part.extend_from_slice(&signature_noise_message[..]);
        self.encrypt_and_hash(&mut signature_part)?;
        let ephemeral_plus_static_encrypted_length =
            ELLSWIFT_ENCODING_SIZE + ENCRYPTED_ELLSWIFT_ENCODING_SIZE;
        out[ephemeral_plus_static_encrypted_length..(INITIATOR_EXPECTED_HANDSHAKE_MESSAGE_SIZE)]
            .copy_from_slice(&signature_part[..ENCRYPTED_SIGNATURE_NOISE_MESSAGE_SIZE]);

        // 9. return pair of CipherState objects, the first for encrypting transport messages from
        //    initiator to responder, and the second for messages in the other direction:
        let ck = self.get_ck();
        let (mut temp_k1, mut temp_k2) = Self::hkdf_2(ck, &[]);
        let c1 = ChaCha20Poly1305::new(Key::from_slice(&temp_k1[..]));
        let c2 = ChaCha20Poly1305::new(Key::from_slice(&temp_k2[..]));
        let c1: Cipher<ChaCha20Poly1305> = Cipher::from_key_and_cipher(temp_k1, c1);
        let c2: Cipher<ChaCha20Poly1305> = Cipher::from_key_and_cipher(temp_k2, c2);
        let to_send = out;
        let mut encryptor = c2;
        let mut decryptor = c1;
        encryptor.erase_k();
        decryptor.erase_k();
        // The ciphers keep the only copies of the session keys from here on; `erase_k` above wiped
        // the copies the `Cipher`s carried, and these are the ones the handshake used.
        temp_k1.zeroize();
        temp_k2.zeroize();
        let engine = crate::NoiseEngine {
            encryptor,
            decryptor,
        };
        Ok((to_send, engine))
    }

    // Securely erases sensitive data in the responder's memory.
    //
    // Zeroizes the handshake key (`k`), the chaining key (`ck`) and the handshake
    // hash (`h`), and non-securely erases the ephemeral and static keypairs. The certificate is
    // not secret and is left in place. This function is typically called when the [`Responder`]
    // instance is no longer needed or before deallocation.
    //
    // It does not touch `handshake_cipher`: that key is wiped by [`ChaCha20Poly1305`]'s own
    // zeroize-on-drop. Nor does it reach the transport session ciphers, which by then live in the
    // [`NoiseEngine`] returned by [`Self::step_1`] and are wiped when that is dropped.
    fn erase(&mut self) {
        self.handshake_cipher = None;
        self.k.zeroize();
        self.ck.zeroize();
        self.h.zeroize();
        self.e.non_secure_erase();
        self.s.non_secure_erase();
    }
}

impl Drop for Responder {
    /// Ensures that sensitive data is securely erased when the [`Responder`] instance is dropped,
    /// preventing any potential leakage of cryptographic material.
    fn drop(&mut self) {
        self.erase();
    }
}

#[cfg(test)]
mod test {

    use super::*;

    fn make_responder() -> Box<Responder> {
        use rand::{rngs::StdRng, SeedableRng};
        use secp256k1::Secp256k1;

        let secp = Secp256k1::new();
        let mut rng = StdRng::seed_from_u64(42);
        let authority = Keypair::new(&secp, &mut rng);

        Responder::new_with_now_rng(authority, 60, 100, &mut rng)
    }

    #[test]
    #[cfg_attr(miri, ignore)]
    fn new_certifies_the_static_key_from_the_given_time() {
        use rand::{rngs::StdRng, SeedableRng};
        use secp256k1::Secp256k1;

        let mut rng = StdRng::seed_from_u64(7);
        let authority = Keypair::new(&Secp256k1::new(), &mut rng);
        let responder = Responder::new_with_now_rng(authority, 60, 100, &mut rng);

        assert_eq!(responder.certificate.valid_from, 100);
        assert_eq!(responder.certificate.not_valid_after, 160);
        assert!(responder.certificate.verify_with_now(
            &responder.s.x_only_public_key().0,
            &authority.x_only_public_key().0,
            100,
        ));
    }

    #[test]
    #[cfg_attr(miri, ignore)]
    fn responder_step_1_returns_valid_message_and_engine() {
        use secp256k1::ellswift::ElligatorSwift;

        let responder = make_responder();

        let fake_initiator_ephemeral =
            ElligatorSwift::from_pubkey(responder.e.public_key()).to_array();

        let (msg, _) = responder.step_1(fake_initiator_ephemeral).unwrap();

        assert_eq!(msg.len(), INITIATOR_EXPECTED_HANDSHAKE_MESSAGE_SIZE);
    }

    #[test]
    #[cfg_attr(miri, ignore)]
    fn responder_erase_zeroes_ck_and_h() {
        let mut responder = make_responder();
        assert!(responder.ck.iter().any(|b| *b != 0));
        assert!(responder.h.iter().any(|b| *b != 0));

        responder.erase();

        assert_eq!(responder.ck, [0u8; 32]);
        assert_eq!(responder.h, [0u8; 32]);
    }

    #[test]
    #[cfg_attr(miri, ignore)]
    fn responder_cipher_detects_tampering() {
        use secp256k1::ellswift::ElligatorSwift;

        let responder = make_responder();

        let fake_initiator_ephemeral =
            ElligatorSwift::from_pubkey(responder.e.public_key()).to_array();

        let (_msg, mut engine) = responder.step_1(fake_initiator_ephemeral).unwrap();

        let mut data = vec![10, 20, 30];
        engine.encrypt(&mut data).unwrap();

        data[0] ^= 0x01;

        assert!(engine.decrypt(&mut data).is_err());
    }

    #[test]
    #[cfg_attr(miri, ignore)]
    fn responder_drop_erases_handshake_secrets() {
        // Leaked on purpose: the allocation has to outlive the drop to be inspected.
        let mut responder = core::mem::ManuallyDrop::new(make_responder());
        assert!(responder.ck.iter().any(|b| *b != 0));

        // SAFETY: dropped once, and the fields read below are plain arrays in live memory.
        unsafe { core::ptr::drop_in_place(&mut **responder) };

        assert_eq!(responder.ck, [0u8; 32]);
        assert_eq!(responder.h, [0u8; 32]);
    }
}
